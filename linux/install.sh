#!/usr/bin/env bash
# dshot installer for Linux. Installs for the current user only (no files outside $HOME except
# distro packages). Tested targets: Arch/CachyOS (pacman) and Linux Mint/Ubuntu/Debian (apt).
#
#   ./install.sh                 interactive
#   ./install.sh --yes           accept defaults (start at login, bind Print Screen)
#   ./install.sh --no-deps       skip installing distro packages
set -euo pipefail

ASSUME_YES=0
INSTALL_DEPS=1
for arg in "$@"; do
  case "$arg" in
    -y|--yes) ASSUME_YES=1 ;;
    --no-deps) INSTALL_DEPS=0 ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA="${XDG_DATA_HOME:-$HOME/.local/share}"
PREFIX="$DATA/dshot"
BIN_DIR="$HOME/.local/bin"
LAUNCHER="$BIN_DIR/dshot"
APPS="$DATA/applications"
ICON_DIR="$DATA/icons/hicolor/256x256/apps"

say() { printf '\033[1m==> %s\033[0m\n' "$*"; }
ask() {  # ask "question" default(y/n)
  local answer default="$2"
  if [ "$ASSUME_YES" = 1 ] || [ ! -t 0 ]; then [ "$default" = y ]; return; fi
  read -r -p "$1 [$( [ "$default" = y ] && echo Y/n || echo y/N )] " answer
  answer="${answer:-$default}"
  [[ "$answer" =~ ^[Yy] ]]
}

install_packages() {
  if command -v pacman >/dev/null; then
    say "Installing packages with pacman (Arch / CachyOS)"
    sudo pacman -S --needed --noconfirm pyside6 python-jeepney tesseract tesseract-data-eng tesseract-data-spa
  elif command -v apt-get >/dev/null; then
    say "Installing packages with apt (Linux Mint / Ubuntu / Debian)"
    sudo apt-get update -qq
    # PySide6 is not packaged on Ubuntu 24.04 / Mint 22; it is installed with pip below.
    sudo apt-get install -y python3 python3-venv python3-jeepney libxcb-cursor0 \
      tesseract-ocr tesseract-ocr-eng tesseract-ocr-spa
  elif command -v dnf >/dev/null; then
    say "Installing packages with dnf (Fedora)"
    sudo dnf install -y python3-pyside6 python3-jeepney tesseract tesseract-langpack-eng tesseract-langpack-spa
  else
    echo "Unknown distribution: install Python 3, PySide6, jeepney and Tesseract (eng, spa) yourself." >&2
  fi
}

python_ok() {
  "$1" -c 'import PySide6.QtWidgets, PySide6.QtSvg, PySide6.QtNetwork, jeepney' 2>/dev/null
}

[ "$INSTALL_DEPS" = 1 ] && install_packages

say "Setting up Python"
PY="$(command -v python3 || true)"
[ -n "$PY" ] || { echo "python3 not found." >&2; exit 1; }
if python_ok "$PY"; then
  echo "Using system Python with PySide6."
else
  echo "PySide6 not available from the system; installing it in $PREFIX/venv (about 100 MB)."
  "$PY" -m venv --system-site-packages "$PREFIX/venv"
  "$PREFIX/venv/bin/pip" install --quiet --upgrade pip
  "$PREFIX/venv/bin/pip" install --quiet PySide6-Essentials jeepney
  PY="$PREFIX/venv/bin/python"
  python_ok "$PY" || { echo "PySide6 installation failed." >&2; exit 1; }
fi

say "Installing dshot to $PREFIX"
"$LAUNCHER" --quit >/dev/null 2>&1 || true  # Stop a running copy before replacing it.
mkdir -p "$PREFIX" "$BIN_DIR" "$APPS" "$ICON_DIR"
rm -rf "$PREFIX/app"
mkdir -p "$PREFIX/app"
cp -r "$SRC/dshot" "$PREFIX/app/"
find "$PREFIX/app" -name '__pycache__' -prune -exec rm -rf {} +
cp "$SRC/uninstall.sh" "$PREFIX/uninstall.sh"
chmod +x "$PREFIX/uninstall.sh"

cat > "$LAUNCHER" <<EOF
#!/bin/sh
# dshot launcher (generated by install.sh)
export DSHOT_LAUNCHER="$LAUNCHER"
export PYTHONPATH="$PREFIX/app\${PYTHONPATH:+:\$PYTHONPATH}"
exec "$PY" -m dshot "\$@"
EOF
chmod +x "$LAUNCHER"

cp "$SRC/dshot/assets/dshot.png" "$ICON_DIR/dshot.png"
cat > "$APPS/dshot.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=dshot
GenericName=Screenshot tool
Comment=Screenshot, annotation and OCR
Exec=$LAUNCHER
Icon=dshot
Terminal=false
Categories=Utility;Graphics;
Keywords=screenshot;capture;ocr;
Actions=Capture;

[Desktop Action Capture]
Name=Capture
Exec=$LAUNCHER --capture
EOF
if command -v update-desktop-database >/dev/null; then update-desktop-database -q "$APPS" 2>/dev/null || true; fi
if command -v gtk-update-icon-cache >/dev/null; then gtk-update-icon-cache -q -t "$DATA/icons/hicolor" 2>/dev/null || true; fi

if ask "Start dshot automatically at login?" y; then
  mkdir -p "${XDG_CONFIG_HOME:-$HOME/.config}/autostart"
  cat > "${XDG_CONFIG_HOME:-$HOME/.config}/autostart/dshot.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=dshot
Comment=Screenshot, annotation and OCR
Exec="$LAUNCHER"
Icon=dshot
Terminal=false
X-GNOME-Autostart-enabled=true
EOF
fi

# ----- Print Screen -----
bind_cinnamon() {
  local schema=org.cinnamon.desktop.keybindings
  local path=/org/cinnamon/desktop/keybindings/custom-keybindings/dshot/
  gsettings list-schemas 2>/dev/null | grep -qx "$schema" || return 1
  # Remember Cinnamon's own screenshot key once, so a reinstall never overwrites the original.
  [ -f "$PREFIX/cinnamon-screenshot-binding.bak" ] ||
    gsettings get $schema.media-keys screenshot > "$PREFIX/cinnamon-screenshot-binding.bak" || return 1
  gsettings set "$schema.custom-keybinding:$path" name 'dshot' || return 1
  gsettings set "$schema.custom-keybinding:$path" command "$LAUNCHER --capture" || return 1
  gsettings set "$schema.custom-keybinding:$path" binding "['Print']" || return 1
  local list
  list="$(gsettings get $schema custom-list)" || return 1
  list="$("$PY" -c 'import ast,sys; v=sys.argv[1].replace("@as ",""); l=ast.literal_eval(v); l+=[] if "dshot" in l else ["dshot"]; print(l)' "$list")" || return 1
  gsettings set $schema custom-list "$list" || return 1
  gsettings set $schema.media-keys screenshot "@as []" || return 1  # Free Print (uninstall.sh restores it).
  echo "Print Screen now opens dshot."
}

bind_kde() {
  local kw kr
  kw="$(command -v kwriteconfig6 || command -v kwriteconfig5 || true)"
  kr="$(command -v kreadconfig6 || command -v kreadconfig5 || true)"
  [ -n "$kw" ] && [ -n "$kr" ] || return 1
  # Remember Spectacle's key once (empty means "default"), so uninstall.sh can put it back.
  [ -f "$PREFIX/kde-spectacle-binding.bak" ] ||
    "$kr" --file kglobalshortcutsrc --group services --group org.kde.spectacle.desktop --key _launch \
      > "$PREFIX/kde-spectacle-binding.bak" || return 1
  "$kw" --file kglobalshortcutsrc --group services --group dshot.desktop --key Capture "Print" || return 1
  "$kw" --file kglobalshortcutsrc --group services --group org.kde.spectacle.desktop --key _launch "none" || return 1
  echo "Print Screen is set to dshot; it takes effect after you log out and back in."
}

print_manual_binding() {
  cat <<EOF
To use Print Screen, add a custom shortcut in your desktop's keyboard settings:
  command:  $LAUNCHER --capture
  key:      Print   (remove Print from the built-in screenshot tool first)
EOF
}

DESKTOP="${XDG_CURRENT_DESKTOP:-}"
if ask "Use the Print Screen key for dshot (replaces the desktop's screenshot key)?" y; then
  case "$DESKTOP" in
    *Cinnamon*|*CINNAMON*) bind_cinnamon || print_manual_binding ;;
    *KDE*) bind_kde || print_manual_binding ;;
    *) print_manual_binding ;;
  esac
else
  print_manual_binding
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) echo "Note: $BIN_DIR is not in your PATH; use the app menu or the full path $LAUNCHER." ;;
esac

say "Starting dshot"
nohup "$LAUNCHER" >/dev/null 2>&1 &
echo "Done. Left-click the dshot tray icon or press Print Screen to capture."
echo "To uninstall: $PREFIX/uninstall.sh"
